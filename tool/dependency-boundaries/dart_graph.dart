import "dart:collection";

import "package:analyzer/dart/analysis/utilities.dart";
import "package:analyzer/dart/ast/ast.dart";

enum DependencyKind { import, export, part }

class DartDependency {
  const DartDependency({
    required this.source,
    required this.target,
    required this.line,
    required this.kind,
    this.via = const [],
  });

  final String source;
  final String target;
  final int line;
  final DependencyKind kind;
  final List<String> via;
}

class DartModule {
  const DartModule({
    required this.path,
    required this.dependencies,
    required this.lines,
    required this.declarations,
    required this.isGeneratedBridge,
  });

  final String path;
  final List<DartDependency> dependencies;
  final int lines;
  final List<String> declarations;
  final bool isGeneratedBridge;
}

String resolveDartDependency(String source, String literal) {
  final uri = Uri.parse(literal);
  if (uri.hasQuery || uri.hasFragment || uri.hasAuthority) {
    throw FormatException("Unsupported dependency URI in $source: $literal");
  }
  if (uri.scheme == "package") {
    const packagePrefix = "cedarflake_ame/";
    if (!uri.path.startsWith(packagePrefix)) return uri.toString();
    return Uri(
      path: "lib/",
    ).resolve(uri.path.substring(packagePrefix.length)).normalizePath().path;
  }
  if (uri.scheme == "dart") return uri.toString();
  if (uri.hasScheme || uri.path.startsWith("/")) {
    throw FormatException(
      "Dependency must use a portable URI: $source -> $literal",
    );
  }
  return Uri(path: source).resolveUri(uri).normalizePath().path;
}

DartModule parseDartModule(
  String path,
  String source, {
  bool isGeneratedBridge = false,
}) {
  if (isGeneratedBridge &&
      (!path.startsWith("lib/src/rust/") ||
          !(source.startsWith("// This file is automatically generated") ||
              source.startsWith(
                "// GENERATED CODE - DO NOT MODIFY BY HAND",
              )))) {
    throw FormatException(
      "The admitted bridge output lost its generated identity: $path",
    );
  }
  final dependencies = <DartDependency>[];
  final declarations = <String>[];
  if (!isGeneratedBridge) {
    final parsed = parseString(content: source, path: path);
    for (final directive in parsed.unit.directives) {
      if (directive is! UriBasedDirective) continue;
      final kind = switch (directive) {
        ImportDirective() => DependencyKind.import,
        ExportDirective() => DependencyKind.export,
        PartDirective() => DependencyKind.part,
      };
      final uris = [
        directive.uri,
        if (directive is NamespaceDirective)
          ...directive.configurations.map((configuration) => configuration.uri),
      ];
      for (final uri in uris) {
        final value = uri.stringValue;
        if (value == null || value.isEmpty) {
          throw FormatException("Unresolved dependency URI in $path");
        }
        dependencies.add(
          DartDependency(
            source: path,
            target: resolveDartDependency(path, value),
            line: parsed.lineInfo.getLocation(uri.offset).lineNumber,
            kind: kind,
          ),
        );
      }
    }
    for (final declaration in parsed.unit.declarations) {
      switch (declaration) {
        case ClassDeclaration():
          declarations.add(declaration.namePart.typeName.lexeme);
        case FunctionDeclaration():
          declarations.add(declaration.name.lexeme);
        case TopLevelVariableDeclaration():
          declarations.addAll(
            declaration.variables.variables.map(
              (variable) => variable.name.lexeme,
            ),
          );
      }
    }
  }
  return DartModule(
    path: path,
    dependencies: dependencies,
    lines: source.split("\n").length - (source.endsWith("\n") ? 1 : 0),
    declarations: declarations,
    isGeneratedBridge: isGeneratedBridge,
  );
}

Iterable<DartDependency> exposedDependencies(
  DartModule module,
  Map<String, DartModule> modules,
) sync* {
  for (final direct in module.dependencies) {
    yield direct;
    final visited = <String>{module.path, direct.target};
    final pending = Queue<(String, List<String>)>()
      ..add((direct.target, const []));
    while (pending.isNotEmpty) {
      final (target, via) = pending.removeFirst();
      for (final exported
          in modules[target]?.dependencies ?? <DartDependency>[]) {
        if (exported.kind != DependencyKind.export) continue;
        if (!visited.add(exported.target)) continue;
        final chain = [...via, target];
        yield DartDependency(
          source: module.path,
          target: exported.target,
          line: direct.line,
          kind: direct.kind,
          via: chain,
        );
        pending.add((exported.target, chain));
      }
    }
  }
}

List<List<String>> dependencyCycles(Map<String, DartModule> modules) {
  var nextIndex = 0;
  final indices = <String, int>{};
  final lowLinks = <String, int>{};
  final stack = <String>[];
  final active = <String>{};
  final cycles = <List<String>>[];

  void visit(String path) {
    indices[path] = nextIndex;
    lowLinks[path] = nextIndex++;
    stack.add(path);
    active.add(path);
    final targets =
        modules[path]?.dependencies.map((edge) => edge.target).toSet() ??
        <String>{};
    for (final target in targets) {
      if (!modules.containsKey(target)) continue;
      if (!indices.containsKey(target)) {
        visit(target);
        if (lowLinks[target]! < lowLinks[path]!) {
          lowLinks[path] = lowLinks[target]!;
        }
      } else if (active.contains(target) &&
          indices[target]! < lowLinks[path]!) {
        lowLinks[path] = indices[target]!;
      }
    }
    if (lowLinks[path] != indices[path]) return;
    final component = <String>[];
    String member;
    do {
      member = stack.removeLast();
      active.remove(member);
      component.add(member);
    } while (member != path);
    if (component.length > 1 || targets.contains(path)) {
      cycles.add(component..sort());
    }
  }

  for (final path in modules.keys.toList()..sort()) {
    if (!indices.containsKey(path)) visit(path);
  }
  return cycles;
}
